-- V9: 결제 수단 분리
--
-- 명세의 결제 모델은 포인트 전액 차감이다(529~532p). 그 위에 카드 결제를 더한다. (D31)
--
-- 강사가 "쇼핑몰이 아닌 자유주제도 가능"이라고 열어줬으므로 결제 모델도 정할 수 있다.
-- 실제 뷰티 커머스는 이렇게 동작한다.
--
--   결제 금액 = 상품 총액 - 사용한 포인트
--   적립      = 실제로 낸 금액(카드분) × 적립률
--
-- 포인트로 낸 부분에는 적립하지 않는다. 적립하면 포인트가 포인트를 낳아
-- 결제 없이 잔액이 늘어난다.

-- 이 주문에서 포인트로 낸 금액.
--
-- total_amount는 상품 총액이고, 그중 얼마를 포인트로 냈는지를 따로 둔다.
-- 취소할 때 이 값이 있어야 "포인트로 얼마를 돌려주고 카드로 얼마를 환불할지"를 나눌 수 있다.
-- 없으면 전액을 포인트로 돌려주게 되어 카드로 낸 돈만큼 포인트가 늘어난다.
ALTER TABLE order_item ADD COLUMN used_point BIGINT NOT NULL DEFAULT 0;

-- 포인트 사용액은 상품 총액을 넘을 수 없다. 넘으면 거스름돈이 포인트로 생긴다.
ALTER TABLE order_item ADD CONSTRAINT ck_order_item_used_point
    CHECK (used_point >= 0 AND used_point <= total_amount);
