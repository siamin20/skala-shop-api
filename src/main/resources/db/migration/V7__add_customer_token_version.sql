-- V7: 토큰 버전
--
-- 로그아웃이 리프레시 토큰을 실제로 무효화하게 만든다. (D25)
--
-- 그동안 로그아웃은 쿠키만 만료시켰다. 브라우저에서는 사라지지만 **토큰 자체는 그대로
-- 유효했다.** 공격자가 이미 토큰을 확보했다면 사용자가 로그아웃해도 최대 14일 동안
-- 액세스 토큰을 계속 재발급받을 수 있었다.
--
-- JWT는 그 자체로 유효성을 담고 있어 발급 후 회수할 방법이 없다.
-- 회수하려면 서버가 무언가를 기억해야 하고, 그 최소 단위가 이 숫자다.
--
-- 폐기 목록(blacklist)을 두는 방법도 있지만 발급된 토큰 수만큼 행이 늘고
-- 만료된 것을 지우는 배치가 따로 필요하다. 버전 하나면 고객당 8바이트로 끝난다.
--
-- 번호를 V4가 아니라 V7로 건너뛴 이유: 이 브랜치는 인증 작업 중이라 V4~V6이 아직 없다.
-- 뒤따르는 브랜치들이 그 번호를 이미 쓰고 있어서, V4로 만들면 합칠 때 같은 번호의
-- 다른 파일이 둘이 된다. Flyway는 번호가 연속일 것을 요구하지 않는다.
ALTER TABLE customer ADD COLUMN token_version BIGINT NOT NULL DEFAULT 0;
