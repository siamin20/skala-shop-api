-- V7: 토큰 버전
--
-- 로그아웃이 리프레시 토큰을 실제로 무효화하게 만든다. (D25)
--
-- 그동안 로그아웃은 쿠키만 만료시켰다. 브라우저에서는 사라지지만 **토큰 자체는 그대로
-- 유효했다.** 공격자가 이미 토큰을 확보했다면 사용자가 로그아웃해도 최대 14일 동안
-- 액세스 토큰을 계속 재발급받을 수 있었다.
--
-- JWT는 그 자체로 유효성을 담고 있어 발급 후 회수할 방법이 없다.
-- 회수하려면 서버가 무언가를 기억해야 하고, 그 최소 단위가 이 숫자다.
--
-- 폐기 목록(blacklist)을 두는 방법도 있지만 발급된 토큰 수만큼 행이 늘고
-- 만료된 것을 지우는 배치가 따로 필요하다. 버전 하나면 고객당 8바이트로 끝난다.
--
-- ── 번호를 V7로 건너뛴 이유와 그 위험 ──
--
-- 이 브랜치는 인증 작업 중이라 V4~V6이 아직 없다. 뒤따르는 브랜치들이 그 번호를
-- 이미 쓰고 있어서, V4로 만들면 합칠 때 같은 번호의 다른 파일이 둘이 된다.
--
-- 다만 번호를 건너뛰면 out-of-order 문제가 생길 수 있다.
-- **이 브랜치를 먼저 적용한 DB에 나중에 V4~V6이 합쳐지는 경우**다.
-- 그 DB의 현재 버전은 7인데 V4~V6이 "해결됐지만 적용되지 않은" 상태로 남아,
-- 기본 설정(out-of-order: false)에서는 다음 기동이 이렇게 실패한다.
--
--   Detected resolved migration not applied to database
--
-- 그런 DB가 있는지 확인했다. **없다.**
--   - local은 H2 인메모리라 기동할 때마다 새로 만든다
--   - 테스트는 Testcontainers로 매번 새 컨테이너를 띄운다
--   - prod에 해당하는 영속 DB는 아직 존재하지 않는다
--
-- 그래서 out-of-order를 켜지 않는다. 켜면 "마이그레이션은 순서대로 적용된다"는
-- 보장이 영구히 약해진다. 한 번의 병합 편의를 위해 치를 대가가 아니다.
--
-- 스택이 전부 합쳐지면 V1~V7이 빈틈없이 이어지므로, 새로 만드는 DB에는
-- 애초에 이 문제가 없다.
--
-- 만약 중간 브랜치를 적용한 DB가 생긴다면 그것을 버리고 다시 만든다.
