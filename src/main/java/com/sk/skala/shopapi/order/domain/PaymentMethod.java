package com.sk.skala.shopapi.order.domain;

/**
 * 결제 수단. (D31)
 *
 * <p>명세의 결제 모델은 포인트 전액 차감이다. 강사가 자유주제를 열어줬으므로
 * 실제 커머스에 가까운 카드 결제를 더했다.
 */
public enum PaymentMethod {

    /**
     * 포인트 전액 결제. <b>명세(529~532p)의 기본 동작이다.</b>
     *
     * <p>요청에 결제 수단을 적지 않으면 이쪽이다. 명세대로 호출한 요청이
     * 그대로 동작해야 하기 때문이다.
     *
     * <p>적립은 없다. 포인트로 낸 금액에 적립하면 포인트가 포인트를 낳아
     * 결제 없이 잔액이 늘어난다.
     */
    POINT,

    /**
     * 카드 결제. 포인트를 일부 사용해 할인할 수 있다.
     *
     * <p>실제 카드사 연동은 하지 않는다. 외부 결제는 PG 계약과 인증이 필요해
     * 과제 범위를 넘어서고, 그것을 흉내 내는 코드는 검증할 수 없는 껍데기가 된다.
     * <b>승인은 항상 성공한 것으로 다룬다.</b>
     *
     * <p>대신 <b>금액 계산과 적립·환불 규칙은 실제와 같게</b> 구현했다.
     * 그쪽이 이 프로젝트에서 검증할 수 있는 부분이다.
     */
    CARD
}
